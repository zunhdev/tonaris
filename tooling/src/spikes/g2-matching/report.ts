// The TON-18 tables: the corpus, same-title pairs under both rules, step 2's multi-album links, steps 3 and 4 by
// service and edition kind, the cases to read, and where track links landed.

import type { Edition, ReleaseGroup } from "./corpus";
import type { Outcome, Truth } from "./evaluate";

type Corpus = {
  base: string[];
  missing: string[];
  artists: Record<string, { name: string; groups?: number; skipped?: string }>;
  releaseGroups: Record<string, ReleaseGroup & { artistId: string }>;
  editions: Edition[];
  sameTitle: { artist: string; members: string[] }[];
};

type Results = {
  pairs: {
    truths: Truth[];
    score: {
      pairs: number;
      releaseGroup: { right: number; splits: number };
      similarity: { right: number; wrongMerges: number };
    };
  };
  step2: { link: string; albums: string[] }[];
  identified: {
    link: string;
    service: string;
    releaseGroupId: string;
    kinds: string[];
    outcome: Outcome;
    found: Record<string, string>;
    note?: string;
  }[];
  tracks: {
    link: string;
    outcome: string;
    album?: { title: string; primaryType: string | null; secondaryTypes: string[] };
  }[];
};

const outcomes: readonly Outcome[] = [
  "right",
  "split",
  "wrong",
  "several",
  "none",
  "no bridge",
  "error",
];

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

const count = <T>(items: readonly T[], test: (item: T) => boolean) => items.filter(test).length;

/** A row's label and size, then how many of the group ended in each outcome. */
const outcomeRow = (label: string, group: readonly { outcome: Outcome }[]) =>
  [label, String(group.length)].concat(
    outcomes.map((o) => String(count(group, (r) => r.outcome === o))),
  );

export function buildReport(corpus: Corpus, results: Results): string {
  const name = (id: string) => {
    const g = corpus.releaseGroups[id];
    return g ? `${g.title} (${g.firstReleaseDate?.slice(0, 4) ?? "?"})` : id;
  };
  const artistName = (id: string) =>
    corpus.artists[corpus.releaseGroups[id]?.artistId ?? ""]?.name ?? "";
  const artists = Object.values(corpus.artists);

  const kinds = new Map<string, number>();
  for (const e of corpus.editions) for (const k of e.kinds) kinds.set(k, (kinds.get(k) ?? 0) + 1);

  const { truths, score } = results.pairs;
  const multi = results.step2.filter((s) => s.albums.length > 1);

  const byService = Map.groupBy(results.identified, (r) => r.service);
  const kindRows = [...kinds.keys()].toSorted().map((kind) =>
    outcomeRow(
      kind,
      results.identified.filter((r) => r.kinds.includes(kind)),
    ),
  );

  const cases = results.identified.filter((r) => ["split", "wrong", "several"].includes(r.outcome));
  const trackTypes = new Map<string, number>();
  for (const t of results.tracks) {
    if (!t.album) continue;
    const type = [t.album.primaryType ?? "no type", ...t.album.secondaryTypes].join(" + ");
    trackTypes.set(type, (trackTypes.get(type) ?? 0) + 1);
  }

  return [
    "# TON-18 results",
    "",
    "Generated by `tooling/src/spikes/g2-matching/run.ts` from `corpus.json`.",
    "",
    "## Corpus",
    "",
    `- ${corpus.base.length} albums from the G1 samples, ${corpus.missing.length} of them no longer in MusicBrainz.`,
    `- ${artists.length} artists listed, ${count(artists, (a) => Boolean(a.skipped))} skipped (more than 300 official albums, or not found).`,
    `- ${corpus.editions.length} releases with streaming links, ${corpus.editions.reduce((n, e) => n + e.links.length, 0)} links.`,
    `- ${corpus.sameTitle.length} same-title groups, ${score.pairs} pairs, ${count(truths, (t) => t.reviewed)} reviewed by hand.`,
    "",
    table(
      ["Edition kind", "Releases"],
      [...kinds].toSorted((a, b) => b[1] - a[1]).map(([k, n]) => [k, String(n)]),
    ),
    "",
    "## Same-title pairs",
    "",
    table(
      ["Rule", "Right", "Wrong", "How it fails"],
      [
        [
          "Release group (TS-44)",
          String(score.releaseGroup.right),
          String(score.releaseGroup.splits),
          "splits one album MusicBrainz keeps under two",
        ],
        [
          "Title and artist",
          String(score.similarity.right),
          String(score.similarity.wrongMerges),
          "merges different albums",
        ],
      ],
    ),
    "",
    "One album under two release groups:",
    "",
    ...truths
      .filter((t) => t.same)
      .map(
        (t) =>
          `- ${artistName(t.a)}: ${name(t.a)} / ${name(t.b)}: ${t.note}${t.reviewed ? "" : " (heuristic)"}`,
      ),
    "",
    "## Step 2: links related to several albums",
    "",
    `${multi.length} of ${results.step2.length} edition links MusicBrainz knows relate to releases of more than one album.`,
    "",
    ...multi.map((s) => `- ${s.link}: ${s.albums.map(name).join("; ")}`),
    "",
    "## Steps 3 and 4: edition links without the URL lookup",
    "",
    table(
      ["Service", "Links", ...outcomes],
      [...byService].map(([service, group]) => outcomeRow(service, group)),
    ),
    "",
    table(["Edition kind", "Links", ...outcomes], kindRows),
    "",
    "Split, wrong and several:",
    "",
    ...cases.map(
      (r) =>
        `- ${r.outcome}: ${r.link} (${r.kinds.join(", ")}) belongs to ${name(r.releaseGroupId)}; found ${Object.entries(
          r.found,
        )
          .map(([id, title]) => `${title} \`${id}\``)
          .join("; ")}`,
    ),
    "",
    "Found under a newer id, because MusicBrainz merged the release group since:",
    "",
    ...results.identified
      .filter((r) => r.note?.startsWith("MusicBrainz merged"))
      .map((r) => `- ${r.outcome}: ${r.link}: ${r.note}`),
    "",
    "## Track links (TON-15)",
    "",
    `${count(results.tracks, (t) => t.outcome === "confident")} of ${results.tracks.length} Spotify track links identified an album.`,
    "",
    table(
      ["Album type", "Track links"],
      [...trackTypes].toSorted((a, b) => b[1] - a[1]).map(([t, n]) => [t, String(n)]),
    ),
    "",
  ].join("\n");
}
